def translate_excel():
    excel_path = Path(r"d:\BaiTapCode\WHMX\WhmxCalc\localization\names_vi.xlsx")
    wb = openpyxl.load_workbook(excel_path)
    
    # Translate characters
    ws_chars = wb["characters"]
    for r in range(2, ws_chars.max_row + 1):
        name_cn = ws_chars.cell(r, 2).value
        fullname_cn = ws_chars.cell(r, 3).value
        
        if name_cn in translations:
            ws_chars.cell(r, 8).value = translations[name_cn]
        
        if fullname_cn in translations:
            ws_chars.cell(r, 9).value = translations[fullname_cn]
            
    # Translate items
    ws_items = wb["items"]
    for r in range(2, ws_items.max_row + 1):
        name_cn = ws_items.cell(r, 2).value
        if name_cn in translations:
            ws_items.cell(r, 7).value = translations[name_cn]
            
    # Translate talent_nodes
    ws_nodes = wb["talent_nodes"]
    for r in range(2, ws_nodes.max_row + 1):
        name_cn = ws_nodes.cell(r, 1).value
        if name_cn in translations:
            ws_nodes.cell(r, 3).value = translations[name_cn]
            
    wb.save(excel_path)
    print("Translation applied successfully!")

if __name__ == "__main__":
    translate_excel()
